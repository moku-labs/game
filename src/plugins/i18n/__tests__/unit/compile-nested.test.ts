/**
 * Creates an empty game root in the system temp folder.
 *
 * @returns The path of the root.
 */
async function createRoot(): Promise<string> {
  return await mkdtemp(path.join(tmpdir(), "moku-i18n-nested-"));
}

/**
 * Writes one file of a game, creating its folders.
 *
 * @param root - The game root.
 * @param relative - POSIX path under the root.
 * @param content - A string table, written as JSON, or the raw text.
 */
async function put(
  root: string,
  relative: string,
  content: Record<string, unknown> | string
): Promise<void> {
  const file = path.join(root, ...relative.split("/"));
  const text = typeof content === "string" ? content : `${JSON.stringify(content, undefined, 2)}\n`;

  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, text);
}

/**
 * Writes a sub-feature: its door and one string file per locale given.
 *
 * @param root - The game root.
 * @param dir - POSIX folder of the sub-feature, `features/episodes/ep01`.
 * @param tables - The string table of each locale.
 */
async function subFeature(
  root: string,
  dir: string,
  tables: Readonly<Record<string, Record<string, unknown>>>
): Promise<void> {
  await put(root, `${dir}/index.ts`, "export {};\n");
  for (const [locale, table] of Object.entries(tables)) {
    await put(root, `${dir}/strings/${locale}.json`, table);
  }
}

/**
 * Writes the episodes game: a parent `episodes` with keys of its own, a sub-feature `ep01` (en and ru, one key
 * Russian lacks), a sub-feature `ep02` with English only, a sub-feature `art` with assets and no strings, and a
 * top-level `home`.
 *
 * @returns The root and its generated folder.
 */
async function episodesGame(): Promise<{ root: string; out: string }> {
  const root = await createRoot();

  await put(root, "features/episodes/index.ts", "export {};\n");
  await put(root, "features/episodes/strings/en.json", { "episodes.title": "Episodes" });
  await put(root, "features/episodes/strings/ru.json", { "episodes.title": "Эпизоды" });
  await subFeature(root, "features/episodes/ep01", {
    en: { "ep01.title": "Ward", "ep01.hint": "{n, number} items" },
    ru: { "ep01.title": "Палата" }
  });
  await subFeature(root, "features/episodes/ep02", { en: { "ep02.title": "Hall" } });
  await put(root, "features/episodes/art/index.ts", "export {};\n");
  await put(root, "features/episodes/art/assets/door.png", "png");
  await put(root, "features/home/strings/en.json", { "home.play": "Play" });
  await put(root, "features/home/strings/ru.json", { "home.play": "Играть" });

  return { root, out: path.join(root, "generated") };
}

/**
 * Reads the keys of one generated locale module.
 *
 * @param out - The generated folder.
 * @param file - The module's file name.
 * @returns Its keys, sorted.
 */
async function keysOf(out: string, file: string): Promise<string[]> {
  return Object.keys(evaluateModule(await readFile(path.join(out, file), "utf8"))).toSorted();
}

/**
 * Lists a folder that may not exist.
 *
 * @param folder - The folder.
 * @returns Its file names, sorted; none when it is missing.
 */
async function filesIn(folder: string): Promise<string[]> {
  try {
    const names = await readdir(folder);

    return names.toSorted();
  } catch {
    return [];
  }
}

/**
 * Writes the flat game: features `Board` and `apple` (whose code-unit and `localeCompare` orders differ), a kind
 * folder `apple/views/`, a folder `apple/notes/` with strings but no door, and a code-only `apple/helpers/`.
 *
 * @returns The root and its generated folder.
 */
async function flatGame(): Promise<{ root: string; out: string }> {
  const root = await createRoot();

  await put(root, "features/Board/strings/en.json", { "board.full": "Full" });
  await put(root, "features/Board/strings/ru.json", { "board.full": "Полно" });
  await put(root, "features/apple/strings/en.json", {
    "apple.pick": "Pick {name}",
    "apple.tab": "{id, select, red {Red} other {Any}}"
  });
  await put(root, "features/apple/strings/ru.json", {
    "apple.pick": "Сорвать {name}",
    "apple.tab": "{id, select, green {Зелёное} other {Любое}}"
  });
  await put(root, "features/apple/views/basket.ts", "export const basket = 1;\n");
  await put(root, "features/apple/notes/strings/en.json", { "notes.hidden": "Hidden" });
  await put(root, "features/apple/helpers/index.ts", "export const helper = 1;\n");

  return { root, out: path.join(root, "generated") };
}

describe("compileStrings with sub-features", () => {
  it("walks a sub-feature's strings into the types module", async () => {
    // Bug: the walk still reads one level of features/ only.
    const { root, out } = await episodesGame();
    const report = await compileStrings(root, out);
    const types = await readFile(path.join(out, "strings.ts"), "utf8");

    expect(report.keys).toEqual([
      "ep01.hint",
      "ep01.title",
      "ep02.title",
      "episodes.title",
      "home.play"
    ]);
    expect(types).toContain('"ep01.hint": { n: number };');
    expect(types).toContain('"ep02.title": Record<string, never>;');
  });

  it("splits the keys: a sub-feature's into its own module, the parent's and the rest into the whole-game one", async () => {
    // Bug: the trim is missing, a key lands in both, or the parent is taken for a sub-feature.
    const { root, out } = await episodesGame();

    await compileStrings(root, out);

    expect(await keysOf(out, "strings.en.ts")).toEqual(["episodes.title", "home.play"]);
    expect(await keysOf(out, "strings.ru.ts")).toEqual(["episodes.title", "home.play"]);
    expect(await keysOf(out, "strings.ep01.en.ts")).toEqual(["ep01.hint", "ep01.title"]);
    expect(await keysOf(out, "strings.ep01.ru.ts")).toEqual(["ep01.title"]);
  });

  it("writes a module for every game locale, empty where the sub-feature brought none, and none for a sub-feature without strings", async () => {
    // Bug: import("@generated/strings.ep02.ru") breaks the build, or a sub-feature with art only gets noise modules.
    const { root, out } = await episodesGame();

    await compileStrings(root, out);

    expect(await filesIn(out)).toEqual([
      "strings.en.ts",
      "strings.ep01.en.ts",
      "strings.ep01.ru.ts",
      "strings.ep02.en.ts",
      "strings.ep02.ru.ts",
      "strings.ru.ts",
      "strings.ts"
    ]);
    expect(await keysOf(out, "strings.ep02.ru.ts")).toEqual([]);
  });

  it("names the nested file a locale lacks", async () => {
    // Bug: a note points at the parent's folder instead of the sub-feature's own file.
    const { root, out } = await episodesGame();
    const report = await compileStrings(root, out);

    expect(report.notes).toEqual([
      'the key "ep01.hint" is missing from features/episodes/ep01/strings/ru.json.',
      'the key "ep02.title" is missing from features/episodes/ep02/strings/ru.json.'
    ]);
  });

  it("reports a check run changed when only a per-feature module is stale or missing, and writes nothing", async () => {
    // Bug: `changed` covers only the whole-game modules, so a stale strings.ep01.ru.ts passes the check.
    const { root, out } = await episodesGame();

    await compileStrings(root, out);
    await put(root, "generated/strings.ep01.ru.ts", "// stale\n");

    const stale = await compileStrings(root, out, { check: true });

    expect(stale.changed).toBe(true);
    expect(await readFile(path.join(out, "strings.ep01.ru.ts"), "utf8")).toBe("// stale\n");

    await rm(path.join(out, "strings.ep01.ru.ts"));

    const missing = await compileStrings(root, out, { check: true });

    expect(missing.changed).toBe(true);
    expect(await filesIn(out)).not.toContain("strings.ep01.ru.ts");
  });

  it("refuses a sub-feature key without its prefix and the prefix alone; a top-level key needs none", async () => {
    // Bug: the prefix rule is missing, takes "ep01." for a key, or leaks to a top-level feature ("title" in home).
    const root = await createRoot();

    await put(root, "features/home/strings/en.json", { title: "Home" });
    await subFeature(root, "features/episodes/ep01", {
      en: { "ep01.title": "Ward", title: "Ward", "ep01.": "Ward" }
    });

    await expect(compileStrings(root, path.join(root, "generated"))).rejects.toThrow(
      "[game] i18n: the compile found 2 problems.\n" +
        '  "title" in features/episodes/ep01/strings/en.json: a key of the sub-feature "ep01" starts with "ep01.".\n' +
        '  "ep01." in features/episodes/ep01/strings/en.json: a key of the sub-feature "ep01" starts with "ep01.".\n'
    );
    expect(await filesIn(path.join(root, "generated"))).toEqual([]);
  });

  it("refuses a sub-feature folder whose name a module file name cannot carry", async () => {
    // Bug: generated/strings.ep.01.en.ts is written, and nothing can read its feature and locale back.
    const root = await createRoot();

    await subFeature(root, "features/episodes/ep.01", { en: { "ep.01.title": "Ward" } });

    await expect(compileStrings(root, path.join(root, "generated"))).rejects.toThrow(
      '[game] i18n: features/episodes/ep.01: a sub-feature name is letters, digits, "_" and "-", so generated/strings.<name>.<locale>.ts can be read back.\n'
    );
  });

  it("rejects two sub-features of one name with the error of findFeatureOwners and writes nothing", async () => {
    // Bug: two owners named "kit" merge silently into one strings.kit.<locale>.ts.
    const root = await createRoot();

    await subFeature(root, "features/episodes/kit", { en: { "kit.ok": "OK" } });
    await subFeature(root, "features/home/kit", { en: { "kit.go": "Go" } });

    await expect(compileStrings(root, path.join(root, "generated"))).rejects.toThrow(
      '[game] features: the feature name "kit" is taken by two folders: features/episodes/kit and features/home/kit.'
    );
    expect(await filesIn(path.join(root, "generated"))).toEqual([]);
  });

  it("derives a sub-feature's pseudo module from its English and keeps its keys out of the whole-game one", async () => {
    // Bug: the pseudo entries are not split, so strings.en-XA.ts carries ep01 keys and strings.ep01.en-XA.ts is missing.
    const { root, out } = await episodesGame();
    const report = await compileStrings(root, out, { pseudo: true });

    expect(report.locales).toEqual(["en", "en-XA", "ru"]);
    expect(await keysOf(out, "strings.en-XA.ts")).toEqual(["episodes.title", "home.play"]);
    expect(await keysOf(out, "strings.ep01.en-XA.ts")).toEqual(["ep01.hint", "ep01.title"]);
  });

  it("takes a sub-feature's en.json for --pseudo when no other owner has one", async () => {
    // Bug: the pseudo check reads one level of features/ and refuses a game whose English lives in a sub-feature.
    const root = await createRoot();
    const out = path.join(root, "generated");

    await put(root, "features/episodes/strings/ru.json", { "episodes.title": "Эпизоды" });
    await subFeature(root, "features/episodes/ep01", { en: { "ep01.title": "Ward" } });

    const report = await compileStrings(root, out, { pseudo: true });

    expect(report.locales).toEqual(["en", "en-XA", "ru"]);
    expect(await keysOf(out, "strings.ep01.en-XA.ts")).toEqual(["ep01.title"]);
  });

  it("finds a sub-feature under the features folder the options name", async () => {
    // Bug: the folder name is not passed to findFeatureOwners, which then looks in features/ (R4).
    const root = await createRoot();
    const out = path.join(root, "generated");

    await put(root, "mods/episodes/strings/en.json", { "episodes.title": "Episodes" });
    await subFeature(root, "mods/episodes/ep01", { en: { "ep01.title": "Ward" } });

    await compileStrings(root, out, { features: "mods" });

    expect(await keysOf(out, "strings.ep01.en.ts")).toEqual(["ep01.title"]);
    expect(await keysOf(out, "strings.en.ts")).toEqual(["episodes.title"]);
  });

  it("names the features folder the options name in the --pseudo error", async () => {
    // Bug: the hint says features/ to a game whose features live in mods/.
    const root = await createRoot();

    await put(root, "mods/episodes/strings/ru.json", { "episodes.title": "Эпизоды" });

    await expect(
      compileStrings(root, path.join(root, "generated"), { features: "mods", pseudo: true })
    ).rejects.toThrow(
      "\n  Add mods/<feature>/strings/en.json (a sub-feature's own strings/en.json"
    );
  });
});

describe("compileStrings on a game without sub-features", () => {
  it("writes the same bytes as 0.14.12 and no other file", async () => {
    // Bug: the byte-identical promise breaks, or a door-less or code-only folder inside a feature is walked.
    const { root, out } = await flatGame();

    await compileStrings(root, out);

    expect(await filesIn(out)).toEqual(Object.keys(FLAT_OUTPUT).toSorted());
    for (const [file, text] of Object.entries(FLAT_OUTPUT)) {
      expect(await readFile(path.join(out, file), "utf8")).toBe(text);
    }
  });

  it("walks the features in code-unit order of their folders, as 0.14.12 did", async () => {
    // Bug: the walk follows findFeatureOwners' localeCompare order, so a duplicate is reported against the other file.
    const root = await createRoot();

    await put(root, "features/Board/strings/en.json", { "shared.ok": "OK" });
    await put(root, "features/apple/strings/en.json", { "shared.ok": "OK" });

    await expect(compileStrings(root, path.join(root, "generated"))).rejects.toThrow(
      '[game] i18n: the key "shared.ok" is in features/Board/strings/en.json and features/apple/strings/en.json.\n'
    );
  });

  it("keeps the committed strings of the mini game current, with no module beside them", async () => {
    // Bug: a flat game's generated strings change, or a per-feature module appears for a flat game.
    const out = await createRoot();

    await compileStrings(MINI_GAME, out, { pseudo: true });

    const written = await filesIn(out);
    const generated = await filesIn(path.join(MINI_GAME, "generated"));
    const committed = generated.filter(file => file.startsWith("strings."));

    expect(written).toEqual(committed);
    for (const file of written) {
      expect(await readFile(path.join(out, file), "utf8")).toBe(
        await readFile(path.join(MINI_GAME, "generated", file), "utf8")
      );
    }
  });
});
